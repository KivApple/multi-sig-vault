import { getAddress, isHex, type Address, type Hex } from "viem";
import { findChain } from "@/config/chains";
import { AppError } from "@/lib/errors";
import { sameAddress } from "@/lib/format";
import { packTransfer, unpackTransfer } from "@/lib/qr/transfer";
import { accountId, useAppStore } from "@/store/appStore";
import type { Account, Operation, OpPayload, OpSignature } from "@/types/domain";
import { verifyOperation, verifySignatures } from "./engine";
import { agentAddressOf, getAgentKey, storeAgentKey } from "./hl/common";
import { getOpDefinition } from "./registry";

interface BundleAccount {
	kind: "hl" | "safe";
	env: "mainnet" | "testnet";
	chainId?: number;
	address: string;
	name?: string;
}

/** Wire format of an operation travelling between devices (QR / text). */
interface OpBundle {
	v: 1;
	account: BundleAccount;
	op: Pick<
		Operation,
		"id" | "type" | "params" | "createdAt" | "frozenAt" | "payload" | "signatures" | "owners" | "threshold"
	>;
	/** Agent key generated by the app – QR is a trusted channel, the next device needs it for the result. */
	agentKey?: Hex;
}

export const exportOperation = async (op: Operation, account: Account): Promise<string> => {
	const def = getOpDefinition(op.type);
	const bundle: OpBundle = {
		v: 1,
		account: {
			kind: account.kind,
			env: account.env,
			chainId: account.chainId,
			address: account.address,
			name: account.name,
		},
		op: {
			id: op.id,
			type: op.type,
			params: op.params,
			createdAt: op.createdAt,
			frozenAt: op.frozenAt,
			payload: op.payload,
			signatures: op.signatures,
			owners: op.owners,
			threshold: op.threshold,
		},
		agentKey: def?.hasSecret?.(op.params) ? await getAgentKey(op.id) : undefined,
	};
	return packTransfer(bundle);
};

export type ImportAction = "new" | "merge" | "replace" | "upToDate" | "alreadySent";

export interface ParsedImport {
	account: Account;
	accountIsNew: boolean;
	op: Operation;
	action: ImportAction;
	/** Signatures this import adds to what the device already has. */
	newSignatures: OpSignature[];
	agentKey?: Hex;
}

const isObject = (v: unknown): v is Record<string, unknown> => typeof v === "object" && v !== null && !Array.isArray(v);
const bad = (): never => {
	throw new AppError("import.error.invalid");
};

const parseAccount = (raw: unknown): Account => {
	if (!isObject(raw)) return bad();
	const { kind, env, chainId, address, name } = raw;
	if ((kind !== "hl" && kind !== "safe") || (env !== "mainnet" && env !== "testnet") || typeof address !== "string")
		return bad();
	let checksummed: Address;
	try {
		checksummed = getAddress(address);
	} catch {
		return bad();
	}
	if (kind === "safe") {
		const chain = findChain(typeof chainId === "number" ? chainId : undefined);
		if (!chain) throw new AppError("import.error.chain");
		if (chain.env !== env) return bad();
	}
	return {
		id: accountId(kind, kind === "hl" ? env : (chainId as number), checksummed),
		kind,
		env,
		chainId: kind === "safe" ? (chainId as number) : undefined,
		address: checksummed,
		name: typeof name === "string" ? name.slice(0, 60) : undefined,
		hidden: false,
		hideDust: false,
		addedAt: Date.now(),
	};
};

const parseSignatures = (raw: unknown): OpSignature[] => {
	if (!Array.isArray(raw) || raw.length === 0 || raw.length > 64) return bad();
	return raw.map((s) => {
		if (!isObject(s) || typeof s.signer !== "string" || !isHex(s.signature) || s.signature.length !== 132) return bad();
		return { signer: getAddress(s.signer), signature: s.signature.toLowerCase() as Hex };
	});
};

/**
 * Validates an imported operation completely before anything is stored:
 * structure, known type, payload re-derived from the parameters, every signature recovered.
 */
export const parseImport = async (text: string): Promise<ParsedImport> => {
	const data = await unpackTransfer(text);
	if (!isObject(data) || data.v !== 1 || !isObject(data.op)) return bad();
	const incomingAccount = parseAccount(data.account);
	const raw = data.op;
	if (
		typeof raw.id !== "string" ||
		!/^[0-9a-f-]{36}$/i.test(raw.id) ||
		typeof raw.type !== "string" ||
		!isObject(raw.params) ||
		!isObject(raw.payload)
	) {
		return bad();
	}
	const def = getOpDefinition(raw.type);
	if (!def || def.kind !== incomingAccount.kind) throw new AppError("import.error.unknownType");

	const state = useAppStore.getState();
	const existingAccount = state.accounts.find((a) => a.id === incomingAccount.id);
	const account = existingAccount ?? incomingAccount;
	const owners = Array.isArray(raw.owners) ? raw.owners.map((o) => getAddress(String(o))) : undefined;
	const op: Operation = {
		id: raw.id,
		accountId: account.id,
		type: raw.type,
		params: raw.params,
		status: "signing",
		createdAt: typeof raw.createdAt === "number" ? raw.createdAt : Date.now(),
		frozenAt: typeof raw.frozenAt === "number" ? raw.frozenAt : Date.now(),
		payload: raw.payload as unknown as OpPayload,
		signatures: parseSignatures(raw.signatures),
		owners,
		threshold: typeof raw.threshold === "number" && raw.threshold >= 1 ? Math.floor(raw.threshold) : undefined,
	};
	if (!op.owners || op.owners.length === 0 || !op.threshold || op.threshold > op.owners.length) return bad();
	try {
		verifyOperation(op, account);
	} catch {
		throw new AppError("import.error.mismatch");
	}
	await verifySignatures(op, account);

	let agentKey: Hex | undefined;
	if (def.hasSecret?.(op.params)) {
		const key = data.agentKey;
		if (isHex(key) && key.length === 66 && sameAddress(agentAddressOf(key), String(op.params.agentAddress)))
			agentKey = key;
	}

	const existing = state.operations.find((o) => o.id === op.id);
	let action: ImportAction = "new";
	let newSignatures = op.signatures;
	if (existing) {
		if (existing.status === "sent") action = "alreadySent";
		else if (existing.payload && JSON.stringify(existing.payload) === JSON.stringify(op.payload)) {
			newSignatures = op.signatures.filter((s) => !existing.signatures.some((e) => sameAddress(e.signer, s.signer)));
			action = newSignatures.length > 0 ? "merge" : "upToDate";
		} else action = "replace";
	}
	return { account, accountIsNew: !existingAccount, op, action, newSignatures, agentKey };
};

/** Stores a validated import. */
export const applyImport = async (parsed: ParsedImport): Promise<void> => {
	const store = useAppStore.getState();
	if (parsed.accountIsNew) store.addAccount(parsed.account);
	if (parsed.agentKey && !(await getAgentKey(parsed.op.id))) await storeAgentKey(parsed.op.id, parsed.agentKey);
	if (parsed.action === "new") store.addOperation(parsed.op);
	else if (parsed.action === "replace") store.updateOperation(parsed.op.id, parsed.op);
	else if (parsed.action === "merge") {
		store.updateOperation(parsed.op.id, (current) => ({
			signatures: [...current.signatures, ...parsed.newSignatures],
		}));
	}
};
