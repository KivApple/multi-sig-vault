// Generates src/i18n/dict/{shared,accounts,signers,settings,ops,hl,safe}.ts from strings.mjs.
import { writeFileSync } from "node:fs";
import { STRINGS } from "./strings.mjs";

const FILE_OF = {
	accounts: "accounts",
	signers: "signers",
	settings: "settings",
	ops: "ops",
	import: "ops",
	hl: "hl",
	safe: "safe",
	safeError: "safe",
};
const groups = {};
for (const [key, en, ru] of STRINGS) {
	const file = FILE_OF[key.split(".")[0]] ?? "shared";
	(groups[file] ??= []).push([key, en, ru]);
}
for (const [file, rows] of Object.entries(groups)) {
	const block = (i) => rows.map((r) => `\t\t${JSON.stringify(r[0])}: ${JSON.stringify(r[i])},`).join("\n");
	writeFileSync(
		`src/i18n/dict/${file}.ts`,
		`// Generated by scripts/i18n/generate.mjs from scripts/i18n/strings.mjs – edit the strings there.\nimport { defineDict } from "../define";\n\nexport default defineDict({\n\ten: {\n${block(1)}\n\t},\n\tru: {\n${block(2)}\n\t},\n});\n`,
	);
}
console.log(
	Object.entries(groups)
		.map(([f, r]) => `${f}: ${r.length}`)
		.join(", "),
);
